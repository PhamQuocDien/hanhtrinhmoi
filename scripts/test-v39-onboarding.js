'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { surveyQuestions, placementDefinitions } = require('./migrations/011-v21-survey-placement');
const { validatePlacement } = require('../server/services/diagnostic-validation');
const { choosePreferredPlacement } = require('../assets/platform/placement-matcher');
const { validateSurvey } = require('../server/services/diagnostic-validation');
const root = path.resolve(__dirname, '..');
const questions = surveyQuestions();
const survey = { title: 'Khảo sát V39', description: 'Khảo sát thích ứng theo cấp học, mục tiêu và thói quen học.', version: '39.0.0', status: 'PUBLISHED', questions };
assert.ok(validateSurvey(survey).valid, `Survey seed must pass validation: ${validateSurvey(survey).errors.join('; ')}`);
assert.ok(questions.length >= 25, 'Survey must cover enough dimensions for personalized learning');
assert.ok(questions.some(item => item.code === 'goals' && item.required), 'Learning goals must be required');
assert.ok(questions.some(item => item.code === 'learningFormats' && item.required), 'Learning preferences must be required');
const placements = placementDefinitions();
const discovery = placements.find(item => item.target === 'DISCOVERY');
assert.ok(discovery, 'An unknown-goal learner needs a multi-domain discovery diagnostic');
assert.ok(validatePlacement(discovery).valid, 'The discovery diagnostic must pass placement validation');
assert.ok(discovery.skillSections.length >= 4, 'Discovery diagnostic must sample several different domains');
assert.equal(choosePreferredPlacement(placements, {}, { goals: [] })?.target, 'DISCOVERY', 'Unknown goals must select exploration instead of an arbitrary specialist test');
for (const code of ['university','faculty','field','disciplineGroup','major','specialization','trainingProgram','cohort','academicYear','semester']) {
    const item = questions.find(question => question.code === code);
    assert.ok(item, `Expected existing higher-education question ${code}`);
    assert.deepEqual(item.conditions?.in, ['HIGHER_EDUCATION'], `${code} must only appear for higher education`);
}
const profileHtml = fs.readFileSync(path.join(root, 'profile.html'), 'utf8');
const flowJs = fs.readFileSync(path.join(root, 'assets/platform/flow-pages.js'), 'utf8');
const routes = fs.readFileSync(path.join(root, 'server/routes/platform-routes.js'), 'utf8');
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
assert.equal(packageJson.version, '39.0.0');
assert.match(profileHtml, /Ngày sinh \(không bắt buộc\)/, 'DOB must not block profile completion');
assert.match(profileHtml, /id="university-profile-fields" hidden/, 'University details must start hidden until relevant');
assert.match(flowJs, /if\(values\.birthDate\).*?if\(values\.educationStatus\)/s, 'Profile save must accept a missing date of birth');
assert.match(flowJs, /profile\.html\?onboarding=1/, 'Survey completion must lead to profile review');
assert.match(flowJs, /profile-next-step/, 'Profile must provide a next step after save');
assert.match(routes, /SURVEY_CATALOG_UNAVAILABLE/, 'Survey catalog failure must return a diagnosable error');
assert.match(routes, /ensureDiagnostics\(console\)/, 'Survey endpoint must attempt default survey repair');
console.log(`V39 onboarding checks passed: ${questions.length} survey questions, ${placements.length} diagnostic tracks, multi-domain discovery, conditional higher-education fields, optional DOB, repairable survey catalog and onboarding handoff.`);
