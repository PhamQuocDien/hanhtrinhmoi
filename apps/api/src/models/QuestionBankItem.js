'use strict';
const mongoose = require('mongoose');
const questionBankItemSchema = new mongoose.Schema({
  questionId: { type: String, required: true, unique: true, index: true },
  id: { type: String, required: true },
  grade: { type: Number, required: true, min: 1, max: 12, index: true },
  programCode: { type: String, enum: ['ctst', 'kntt', 'canhdieu'], required: true, index: true },
  subjectCode: { type: String, required: true, index: true },
  courseId: { type: String, required: true, index: true },
  unitId: { type: String, required: true, index: true },
  lessonId: { type: String, required: true, index: true },
  topicTag: { type: String, default: '' },
  topicTitle: { type: String, default: '' },
  purpose: { type: String, enum: ['assessment', 'checkpoint'], default: 'assessment', index: true },
  partId: { type: String, default: '', index: true },
  type: { type: String, enum: ['multiple_choice', 'true_false', 'fill_blank', 'multiple_select', 'matching', 'ordering', 'short_answer', 'essay'], required: true },
  prompt: { type: String, required: true },
  options: { type: [mongoose.Schema.Types.Mixed], default: [] },
  matchingItems: { type: [mongoose.Schema.Types.Mixed], default: [] },
  orderingItems: { type: [mongoose.Schema.Types.Mixed], default: [] },
  contentQualityVersion: { type: String, default: 'V6.1.1' },
  correctAnswer: { type: String, default: '' },
  acceptedAnswers: { type: [String], default: [] },
  points: { type: Number, min: 0, max: 100, default: 1 },
  difficulty: { type: String, enum: ['easy', 'medium', 'hard'], default: 'medium', index: true },
  taxonomy: { type: String, enum: ['remember', 'understand', 'apply', 'analyze', 'create'], default: 'understand', index: true },
  curriculumAlignmentId: { type: String, default: '', index: true },
  mappedStrand: { type: String, default: '' },
  competencyFocus: { type: [String], default: [] },
  intendedOutcomes: { type: [String], default: [] },
  assessmentBlueprint: { type: mongoose.Schema.Types.Mixed, default: () => ({ remember: 25, understand: 35, apply: 25, analyzeCreate: 15 }) },
  alignmentStatus: { type: String, default: 'draft-framework-mapped-teacher-validation-required', index: true },
  source: { type: String, default: 'curriculum-aligned-generated-draft' },
  explanation: { type: String, default: '' },
  rubric: { type: [String], default: [] },
  keyConcepts: { type: [String], default: [] },
  contentStatus: { type: String, default: 'draft-teacher-review-required' },
  bankVersion: { type: String, default: 'V6.1.1' },
  active: { type: Boolean, default: false },
  createdAt: { type: Date, default: Date.now },
  updatedAt: { type: Date, default: Date.now }
}, { versionKey: false });
questionBankItemSchema.index({ grade: 1, programCode: 1, subjectCode: 1, lessonId: 1, partId: 1, purpose: 1, active: 1, type: 1 });
module.exports = mongoose.model('QuestionBankItem', questionBankItemSchema);
